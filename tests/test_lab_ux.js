'use strict';
const A=require('../dashboard/ui/ux.js'),assert=require('node:assert/strict');
const fen='rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1';
assert.equal(A.parseFen(fen).length,8);
assert.equal(A.squares(fen)[0].square,'a8');
assert.equal(A.squares(fen,true)[0].square,'h1');
assert.equal(A.squares(fen,true)[0].piece,'R');
assert.equal(A.squares(fen)[0].light,true);
assert.equal(A.squares(fen,true)[0].light,true);
assert.equal(A.squares(fen,false,'e2e4').filter(x=>x.last).length,2);
assert.equal(A.squares(fen,true).filter(x=>x.file).length,8);
assert.equal(A.squares(fen,true).filter(x=>x.rank).length,8);
assert.throws(()=>A.parseFen('8/8 w'));
assert.throws(()=>A.parseFen('9/8/8/8/8/8/8/8 w'));
assert.equal(A.validateTraining({parallel:9,games_per_iteration:8,arena_games:3}).length,2);
assert.equal(A.validateTraining({parallel:4,games_per_iteration:8,arena_games:0}).length,0);
assert.equal(A.filterCommands([{label:'Новое обучение',keywords:'training new'},{label:'Модели'}],'new обуч').length,1);
assert.equal(A.stepIndex(0,-1,10),0);
assert.equal(A.stepIndex(10,1,10),10);
console.log('16 UX assertions passed');
