'use strict';
const assert=require('node:assert/strict');
const A=require('../dashboard/ui/analytics.js');
const r=A.rows([1,null,0,4,8,'2',Infinity],[10,11,12,13,14,15,16]);
assert.deepEqual(r.map(x=>x.y),[1,null,0,4,8,null,null]);
assert.deepEqual(A.smooth(r,2).map(x=>x.y),[null,null,null,2,6,null,null]);
assert.deepEqual(A.smooth([{x:1,y:2},{x:3,y:4}],2).map(x=>x.y),[null,null]);
assert.deepEqual(A.windowRows(r,3,13).map(x=>x.x),[11,12,13]);
assert.deepEqual(A.windowRows(r,2,null).map(x=>x.x),[15,16]);
assert.deepEqual(A.windowRows(r,3,9),[]);
assert.deepEqual(A.aligned(r,[{x:12,y:5},{x:14,y:0}]).map(x=>x.y),[null,null,5,null,0,null,null]);
assert.equal(A.extent([[{x:1,y:null}]]),null);
assert.ok(A.extent([[{x:1,y:-2},{x:2,y:3}]],0).lo<=-2);
assert.equal(A.outcome({wins:2,draws:2,losses:1,unfinished:3}).score,.6);
assert.equal(A.outcome({wins:0,draws:0,losses:0,unfinished:5}).score,null);
assert.equal(A.outcome({wins:2,draws:0,losses:1}),null);
assert.equal(A.csv([{x:12,y:0,smooth:null,reference:2}]),'iteration,raw,rolling_mean,reference\n12,0,,2\n');
console.log('13 analytics assertions passed');
